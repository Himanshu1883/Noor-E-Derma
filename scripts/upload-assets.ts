import { createReadStream, existsSync, statSync, writeFileSync } from "node:fs"
import path from "node:path"
import { GridFSBucket, ObjectId } from "mongodb"
import mongoose from "mongoose"
import { MediaAsset } from "../src/models/MediaAsset"
import { Product } from "../src/models/Product"

const ROOT = path.resolve(process.cwd())

const USED = [
  { key: "logo", publicPath: "/assets/logo-nd.png", file: "public/assets/logo-nd.png", type: "image/png" },
  { key: "hero1", publicPath: "/assets/hero-1-noor-duo.jpg", file: "public/assets/hero-1-noor-duo.jpg", type: "image/jpeg" },
  { key: "kitTan", publicPath: "/assets/tan-eraser-kit.jpg", file: "public/assets/tan-eraser-kit.jpg", type: "image/jpeg" },
  { key: "cardTan", publicPath: "/assets/card-tan-eraser.jpg", file: "public/assets/card-tan-eraser.jpg", type: "image/jpeg" },
  { key: "cardDetox", publicPath: "/assets/card-daily-detox.jpg", file: "public/assets/card-daily-detox.jpg", type: "image/jpeg" },
] as const

async function uploadOne(bucket: GridFSBucket, abs: string, filename: string, contentType: string) {
  const id = new ObjectId()
  await new Promise<void>((resolve, reject) => {
    const dest = bucket.openUploadStreamWithId(id, filename, {
      metadata: { originalName: filename, contentType },
    })
    dest.on("error", reject)
    dest.on("finish", () => resolve())
    createReadStream(abs).on("error", reject).pipe(dest)
  })
  return String(id)
}

async function main() {
  const uri = process.env.MONGODB_URI
  if (!uri) throw new Error("Set MONGODB_URI in .env.local")

  await mongoose.connect(uri, {
    dbName: process.env.MONGODB_DB || "noor-e-derma",
    serverSelectionTimeoutMS: 12000,
  })
  const db = mongoose.connection.db
  if (!db) throw new Error("Mongo database is not ready")
  const bucket = new GridFSBucket(db, { bucketName: "media" })

  const media: Record<string, string> = {}

  for (const item of USED) {
    const abs = path.join(ROOT, item.file)
    if (!existsSync(abs)) {
      console.warn(`skip missing ${item.file}`)
      continue
    }
    const bytes = statSync(abs).size
    const existing = await MediaAsset.findOne({ key: item.key })
    if (existing?.fileId) {
      try {
        await bucket.delete(new ObjectId(existing.fileId))
      } catch {
        /* first upload or already gone */
      }
    }
    const fileId = await uploadOne(bucket, abs, path.basename(item.file), item.type)
    const src = `/api/media/${fileId}`
    await MediaAsset.findOneAndUpdate(
      { key: item.key },
      {
        key: item.key,
        publicPath: item.publicPath,
        fileId,
        src,
        filename: path.basename(item.file),
        contentType: item.type,
        bytes,
      },
      { upsert: true },
    )
    media[item.publicPath] = src
    console.log(`uploaded ${item.file} (${bytes} bytes) -> ${src}`)
  }

  const products = await Product.find()
  for (const product of products) {
    let changed = false
    const images = (product.images ?? []).map((img) => {
      const plain = typeof img.toObject === "function" ? img.toObject() : img
      const nextSrc = media[plain.src] || plain.src
      const nextPoster = plain.poster ? media[plain.poster] || plain.poster : plain.poster
      if (nextSrc !== plain.src || nextPoster !== plain.poster) changed = true
      return {
        ...plain,
        src: nextSrc,
        poster: nextPoster,
        fileId: nextSrc.startsWith("/api/media/") ? nextSrc.split("/").pop() : plain.fileId,
      }
    })
    if (changed) {
      product.set("images", images)
      await product.save()
      console.log(`updated product ${product.slug}`)
    }
  }

  const entries = USED.map(
    (item) => `  ${JSON.stringify(item.publicPath)}: ${JSON.stringify(media[item.publicPath] ?? item.publicPath)},`,
  ).join("\n")
  writeFileSync(
    path.join(ROOT, "src/data/media-map.ts"),
    `/** Generated by npm run upload-assets — do not edit by hand. */
export const MEDIA: Record<string, string> = {
${entries}
}

export function mediaUrl(publicPath: string) {
  return MEDIA[publicPath] ?? publicPath
}
`,
    "utf8",
  )
  console.log("wrote src/data/media-map.ts")
  console.log("done")
  await mongoose.disconnect()
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err)
  process.exit(1)
})
